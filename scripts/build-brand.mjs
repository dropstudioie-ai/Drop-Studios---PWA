// Builds the Drop Studios logo files from the original stencil letter outlines
// (design/logo/drop-glyphs.json, taken from design/logo/original-DROP_LOGO_BW.svg).
// Logo "P4 · Play Inside": DROP in the original stencil letters, no "studios",
// with an orange play button inside the D.
// Usage: node scripts/build-brand.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const [D, R, O, P] = JSON.parse(readFileSync('design/logo/drop-glyphs.json', 'utf8'));
export const ORANGE = '#FF7A00', INK = '#0B0B0D', BLUE = '#1F43E6';

const glyph = (g) => `<path transform="translate(${g.x} ${g.y})" d="${g.d}"/>`;
// The stencil cuts are real gaps (a mask), so the logo works on any background.
const CUTS = '<rect x="62.4" y="140" width="3.8" height="75"/><rect x="223.1" y="140" width="3.8" height="75"/>';
const PLAY = '<path d="M72.4 164.4 L92.6 176.7 L72.4 189 Z" stroke-width="2.4" stroke-linejoin="round"/>';

const wordmark = (ink, play, id = 'cut') => `
  <defs><mask id="${id}" maskUnits="userSpaceOnUse" x="40" y="135" width="300" height="80">
    <rect x="40" y="135" width="300" height="80" fill="#fff"/><g fill="#000">${CUTS}</g></mask></defs>
  <g fill="${ink}" mask="url(#${id})">${glyph(D)}${glyph(R)}${glyph(O)}${glyph(P)}</g>
  <g fill="${play}" stroke="${play}">${PLAY}</g>`;

const markD = (ink, play, id = 'dcut') => `
  <defs><mask id="${id}" maskUnits="userSpaceOnUse" x="40" y="135" width="80" height="80">
    <rect x="40" y="135" width="80" height="80" fill="#fff"/><g fill="#000"><rect x="62.4" y="140" width="3.8" height="75"/></g></mask></defs>
  <g fill="${ink}" mask="url(#${id})">${glyph(D)}</g>
  <g fill="${play}" stroke="${play}">${PLAY}</g>`;

// Tight boxes around the artwork (original 375×375 artboard units).
export const WORD_BOX = { x: 47, y: 143, w: 285, h: 67 };
const svg = (box, body, extra = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box.x} ${box.y} ${box.w} ${box.h}"${extra}>${body}</svg>\n`;

// App icon: the D-with-play centred on a rounded square.
const iconSvg = (bg, ink, play, { radius = 0.22, scale = 1.5 } = {}) => {
  const r2 = (n) => Math.round(n * 100) / 100;
  const cx = 80.4, cy = 176.7, s = r2(63.2 * scale);
  const x = r2(cx - s / 2), y = r2(cy - s / 2);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${s} ${s}">` +
    `<rect x="${x}" y="${y}" width="${s}" height="${s}" rx="${r2(s * radius)}" fill="${bg}"/>${markD(ink, play)}</svg>\n`;
};

mkdirSync('public/brand', { recursive: true });
writeFileSync('public/brand/drop-logo.svg', svg(WORD_BOX, wordmark(INK, ORANGE)));
writeFileSync('public/brand/drop-logo-white.svg', svg(WORD_BOX, wordmark('#FFFFFF', ORANGE)));
writeFileSync('public/brand/drop-logo-black.svg', svg(WORD_BOX, wordmark(INK, INK)));
writeFileSync('public/brand/drop-icon.svg', iconSvg(BLUE, '#FFFFFF', ORANGE));
writeFileSync('public/brand/drop-icon-black.svg', iconSvg(INK, '#FFFFFF', ORANGE));
writeFileSync('public/brand/drop-icon-maskable.svg', iconSvg(BLUE, '#FFFFFF', ORANGE, { radius: 0, scale: 2.1 }));
writeFileSync('public/favicon.svg', iconSvg(BLUE, '#FFFFFF', ORANGE));

// Path data for the in-app <Logo /> component.
writeFileSync('src/brand/logoData.ts', `// Generated by scripts/build-brand.mjs: do not edit by hand.
export const LOGO_VIEWBOX = '${WORD_BOX.x} ${WORD_BOX.y} ${WORD_BOX.w} ${WORD_BOX.h}';
export const LETTERS = ${JSON.stringify([D, R, O, P].map((g) => ({ x: g.x, y: g.y, d: g.d })))};
export const CUTS = [{ x: 62.4, y: 140, w: 3.8, h: 75 }, { x: 223.1, y: 140, w: 3.8, h: 75 }];
export const PLAY = 'M72.4 164.4 L92.6 176.7 L72.4 189 Z';
`);
console.log('brand files written');
